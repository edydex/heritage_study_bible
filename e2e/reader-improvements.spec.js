test('books remember font size and exact word bookmarks on a black reading background', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('heritage-dark-mode', 'true'))
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/#/resources/books/martyrdom-of-polycarp')
  const paragraph = page.locator('[data-book-paragraph="0"]').first()
  await expect(paragraph).toBeVisible()
  await expect(page.locator('html')).toHaveClass(/dark/)
  await expect(page.getByLabel('Reading font size', { exact: true })).toHaveCount(0)
  await page.locator('header').getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByLabel('Reading font size', { exact: true }).fill('20')
  await page.getByLabel('Reading font size', { exact: true }).press('Enter')
  await page.keyboard.press('Escape')
  expect(await paragraph.evaluate(element => getComputedStyle(element).fontSize)).toBe('20px')
  await page.evaluate(() => {
    const root = document.querySelector('[data-book-paragraph="0"]')
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT)
    const node = walker.nextNode()
    const match = node.textContent.match(/[A-Za-z]{4,}/)
    const range = document.createRange()
    range.setStart(node, match.index)
    range.setEnd(node, match.index + match[0].length)
    const selection = window.getSelection()
    selection.removeAllRanges(); selection.addRange(range)
    document.dispatchEvent(new Event('selectionchange'))
  })
  await expect(page.getByRole('region', { name: 'Selected book text actions' })).toBeVisible()
  await page.getByRole('button', { name: 'Bookmark place' }).click()
  await expect(page.getByText('Place bookmarked.', { exact: true })).toBeVisible()
  await page.reload()
  await expect(paragraph).toBeVisible()
  expect(await paragraph.evaluate(element => getComputedStyle(element).fontSize)).toBe('20px')
  await page.locator('summary').filter({ hasText: 'Bookmarks in this book' }).click()
  await page.locator('details button').filter({ hasText: '“' }).click()
  await expect(page.locator('[data-bookmark-place]')).toBeVisible()
  await page.evaluate(() => document.documentElement.classList.add('dark'))
  const backgrounds = await paragraph.evaluate(element => {
    const colors = []
    while (element) { colors.push(getComputedStyle(element).backgroundColor); element = element.parentElement }
    return colors
  })
  expect(backgrounds).toContain('rgb(0, 0, 0)')
  expect(backgrounds).not.toContain('rgb(31, 41, 55)')
  await page.screenshot({ animations: 'disabled', path: test.info().outputPath('book-dark-phone.png') })
})


