test('book sentence rows seek to the clicked recording position and follow its highlight', async ({ page }) => {
  const { default: catalog } = await import('../src/data/audioCatalog.json', { with: { type: 'json' } })
  const { default: timing } = await import('../public/data/audio/books/martyrdom-of-polycarp.json', { with: { type: 'json' } })
  const track = catalog.books.find(book => book.id === 'martyrdom-of-polycarp').editions[0].tracks[0]
  const spans = timing.tracks[track.id].sentenceSpans
  const first = spans.find((span, index) => span.start > 30 && span.end < 170 && spans[index + 1]?.paragraph === span.paragraph)
  const second = spans[spans.indexOf(first) + 1]
  const wave = Buffer.alloc(44 + 400 * 8000 * 2)
  wave.write('RIFF', 0); wave.writeUInt32LE(wave.length - 8, 4); wave.write('WAVEfmt ', 8)
  wave.writeUInt32LE(16, 16); wave.writeUInt16LE(1, 20); wave.writeUInt16LE(1, 22)
  wave.writeUInt32LE(8000, 24); wave.writeUInt32LE(16000, 28); wave.writeUInt16LE(2, 32); wave.writeUInt16LE(16, 34)
  wave.write('data', 36); wave.writeUInt32LE(wave.length - 44, 40)
  await page.route('https://archive.org/download/**', route => {
    const range = route.request().headers().range?.match(/bytes=(\d+)-(\d*)/)
    const start = Number(range?.[1] || 0), end = range?.[2] ? Math.min(Number(range[2]), wave.length - 1) : wave.length - 1
    return route.fulfill({ status: range ? 206 : 200, contentType: 'audio/wav', body: wave.subarray(start, end + 1), headers: { 'Accept-Ranges': 'bytes', ...(range ? { 'Content-Range': `bytes ${start}-${end}/${wave.length}` } : {}) } })
  })
  await page.addInitScript(({ id, at }) => localStorage.setItem('heritage-audio-progress-v1', JSON.stringify({ lastTrackId: id, positions: { [id]: at }, rate: 1 })), { id: track.id, at: first.start })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(`/#/resources/books/martyrdom-of-polycarp-lake?audioTrack=${track.id}&at=${first.start}`)
  await page.getByLabel('Verse scroll mode').check()
  const target = page.locator(`[data-sentence-start="${second.start}"]`)
  await expect(target).toHaveClass(/reader-sentence-row/)
  await target.click()
  await expect(page.getByRole('button', { name: 'Pause book audio' })).toBeVisible()
  await expect(target).toHaveAttribute('data-audio-sentence', 'true')
  await expect.poll(() => page.evaluate(id => JSON.parse(localStorage.getItem('heritage-audio-progress-v1')).positions[id], track.id)).toBeGreaterThanOrEqual(second.start)
  await page.screenshot({ path: test.info().outputPath('book-sentences-phone.png') })
})
